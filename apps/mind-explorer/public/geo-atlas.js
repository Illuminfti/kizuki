  function drawCartographyLayer(ctx, projectFn, viewState, palette) {
    if (!ctx) return { placedLabels: [], spanLon: 360, activeLayers: [] };

    const vs = viewState || {};
    const pal = resolveAtlasPalette(palette);
    const dpr = Number(vs.dpr) || 1;
    const width = Number(vs.width) || (ctx.canvas ? ctx.canvas.width / dpr : 1000);
    const height = Number(vs.height) || (ctx.canvas ? ctx.canvas.height / dpr : 600);
    const project = buildProjector(projectFn, vs, width, height);
    const { spanLon, zoom, hasExplicitZoom, visibleBBox: vBox } = resolveViewMetrics(ctx, project, vs);
    const activeLayers = ['ocean', 'world-land'];

    const useUkDetailed = spanLon < 22 && bboxIntersects([-11.5, 49.0, 3.0, 61.2], vBox);
    const useLondonMetro =
      (spanLon < 2.6 || (hasExplicitZoom && zoom >= 3.0 && spanLon < 3.4)) &&
      bboxIntersects(LONDON_METRO.bbox, vBox);
    const useAlpsDetail = spanLon < 24 && bboxIntersects(ALPS_EUROPE.bbox, vBox);
    const useUsDetail = spanLon < 62 && bboxIntersects(US_DETAIL.bbox, vBox);

    ctx.save();

    // Layer 1: Bathymetric ocean backdrop with subtle radial depth vignette
    if (vs.skipOceanFill !== true) {
      const cx = width * 0.5, cy = height * 0.48, maxR = Math.max(width, height) * 0.78;
      const oceanGrad = ctx.createRadialGradient(cx, cy, maxR * 0.08, cx, cy, maxR);
      oceanGrad.addColorStop(0, pal.oceanHighlight);
      oceanGrad.addColorStop(0.62, pal.ocean);
      oceanGrad.addColorStop(1, pal.oceanDeep);
      ctx.fillStyle = oceanGrad;
      ctx.fillRect(0, 0, width, height);
    }

    // Layer 2: Landmasses + coastal vignette + crisp shoreline
    const landPolygons = [];
    for (const feat of WORLD_LAND) {
      if (useUkDetailed && feat.detailGroup === 'uk') continue;
      if (bboxIntersects(feat.bbox, vBox)) landPolygons.push(feat);
    }
    if (useUkDetailed) {
      activeLayers.push('uk-detailed');
      for (const feat of UK_DETAILED.polygons) if (bboxIntersects(feat.bbox, vBox)) landPolygons.push(feat);
    }
    if (useUsDetail) {
      for (const feat of US_DETAIL.barrierCoasts) if (bboxIntersects(feat.bbox, vBox)) landPolygons.push(feat);
    }

    const landGrad = ctx.createLinearGradient(0, 0, 0, height);
    landGrad.addColorStop(0, pal.landTop);
    landGrad.addColorStop(1, pal.landBottom);

    ctx.beginPath();
    for (const poly of landPolygons) traceRing(ctx, poly.coords, project, true);

    // 2-pass bathymetric coastal contour shelf halo (zero ctx.filter)
    ctx.save();
    ctx.lineJoin = 'round';
    ctx.strokeStyle = pal.coastOuterHalo;
    ctx.lineWidth = spanLon < 4 ? 10.5 : 7.0;
    ctx.stroke();

    ctx.strokeStyle = pal.coastGlow;
    ctx.lineWidth = spanLon < 4 ? 4.8 : 3.2;
    ctx.stroke();
    ctx.restore();

    ctx.fillStyle = landGrad;
    ctx.fill();
    ctx.strokeStyle = pal.coast;
    ctx.lineWidth = spanLon < 3 ? 1.2 : 1.0;
    ctx.lineJoin = 'round';
    ctx.stroke();

    // Great Lakes water cutouts over North America
    if (bboxIntersects([-93, 41, -75, 49.5], vBox)) {
      ctx.beginPath();
      traceFeatureList(ctx, GREAT_LAKES, project, vBox, true);
      ctx.fillStyle = pal.lakeFill;
      ctx.fill();
      ctx.strokeStyle = pal.coast;
      ctx.lineWidth = 0.75;
      ctx.stroke();
    }

    // Layer 3: Alpine Elevation Contours, Mountain Ridges, Lakes, Rivers & Peaks
    if (useAlpsDetail) {
      activeLayers.push('alps-europe');
      ctx.save();
      ctx.globalAlpha = clamp((24 - spanLon) / 14, 0.25, 1);

      for (const c of ALPS_EUROPE.alpineContours) {
        if ((c.tier === 3 && spanLon > 6.5) || !bboxIntersects(c.bbox, vBox)) continue;
        ctx.beginPath();
        traceRing(ctx, c.coords, project, true);
        ctx.fillStyle = c.tier === 1 ? pal.alpineFill1 : (c.tier === 2 ? pal.alpineFill2 : pal.alpineFill3);
        ctx.fill();
        ctx.strokeStyle = pal.alpineContour;
        ctx.lineWidth = c.tier === 3 ? 0.8 : 0.65;
        ctx.lineJoin = 'round';
        ctx.stroke();
      }

      ctx.beginPath();
      traceFeatureList(ctx, ALPS_EUROPE.ridges, project, vBox, false);
      ctx.strokeStyle = pal.alpineRidge;
      ctx.lineWidth = spanLon < 4 ? 1.05 : 0.8;
      ctx.setLineDash([4, 3]);
      ctx.stroke();
      ctx.setLineDash([]);

      ctx.beginPath();
      for (const lk of ALPS_EUROPE.lakes) {
        if ((lk.id === 'lake-eibsee' && spanLon > 3.5) || !bboxIntersects(lk.bbox, vBox)) continue;
        traceRing(ctx, lk.coords, project, true);
      }
      ctx.fillStyle = pal.lakeFill;
      ctx.fill();
      ctx.strokeStyle = pal.lakeStroke;
      ctx.lineWidth = 0.7;
      ctx.stroke();

      ctx.lineCap = 'round';
      ctx.lineJoin = 'round';
      for (const rv of ALPS_EUROPE.rivers) {
        if ((rv.id === 'river-loisach' && spanLon > 5.0) || !bboxIntersects(rv.bbox, vBox)) continue;
        ctx.beginPath();
        traceRing(ctx, rv.coords, project, false);
        ctx.strokeStyle = pal.riverCasing;
        ctx.lineWidth = spanLon < 3.5 ? 3.0 : 2.0;
        ctx.stroke();
        ctx.strokeStyle = pal.riverCore;
        ctx.lineWidth = spanLon < 3.5 ? 1.25 : 0.85;
        ctx.stroke();
      }

      for (const pk of ALPS_EUROPE.peaks) {
        if (spanLon < pk.minSpan || spanLon > pk.maxSpan) continue;
        const pt = project(pk.lng, pk.lat);
        if (pt[0] < -10 || pt[0] > width + 10 || pt[1] < -10 || pt[1] > height + 10) continue;
        ctx.beginPath();
        ctx.moveTo(pt[0], pt[1] - 3.6);
        ctx.lineTo(pt[0] + 3.2, pt[1] + 2.4);
        ctx.lineTo(pt[0] - 3.2, pt[1] + 2.4);
        ctx.closePath();
        ctx.fillStyle = pal.peakFill;
        ctx.fill();
      }
      ctx.restore();
    }

    // Layer 4: Country & US State Borders
    if (spanLon < 110) {
      ctx.save();
      ctx.lineJoin = 'round';
      ctx.lineCap = 'round';
      if (bboxIntersects([-11, 35, 32, 71], vBox)) {
        ctx.beginPath();
        traceFeatureList(ctx, ALPS_EUROPE.borders, project, vBox, false);
        if (useUkDetailed) traceFeatureList(ctx, UK_DETAILED.borders, project, vBox, false);
        ctx.strokeStyle = pal.border;
        ctx.lineWidth = spanLon < 8 ? 0.95 : 0.75;
        ctx.setLineDash(spanLon < 8 ? [5, 4] : [3, 3]);
        ctx.stroke();
        ctx.setLineDash([]);
      }
      if (useUsDetail) {
        activeLayers.push('us-detail');
        ctx.beginPath();
        traceFeatureList(ctx, US_DETAIL.stateBorders, project, vBox, false);
        ctx.strokeStyle = pal.stateBorder;
        ctx.lineWidth = spanLon < 12 ? 0.9 : 0.7;
        ctx.setLineDash([4, 4]);
        ctx.stroke();
        ctx.setLineDash([]);
      }
      ctx.restore();
    }

    // Layer 5: LONDON_METRO (Parks, Radials, M25 Orbital, Tributaries & River Thames)
    if (useLondonMetro) {
      activeLayers.push('london-metro');
      ctx.save();
      ctx.globalAlpha = clamp((2.0 - spanLon) / 0.85, 0.35, 1);

      ctx.beginPath();
      traceFeatureList(ctx, LONDON_METRO.parks, project, vBox, true);
      ctx.fillStyle = pal.parkFill;
      ctx.fill();
      ctx.strokeStyle = pal.parkStroke;
      ctx.lineWidth = 0.75;
      ctx.stroke();

      ctx.beginPath();
      traceFeatureList(ctx, LONDON_METRO.radials, project, vBox, false);
      ctx.strokeStyle = pal.radialStroke;
      ctx.lineWidth = spanLon < 0.55 ? 1.25 : 0.9;
      ctx.lineCap = 'round';
      ctx.lineJoin = 'round';
      ctx.stroke();

      ctx.beginPath();
      traceRing(ctx, LONDON_METRO.m25, project, true);
      ctx.strokeStyle = pal.m25Stroke;
      ctx.lineWidth = spanLon < 0.65 ? 1.25 : 1.0;
      ctx.setLineDash([5, 4]);
      ctx.stroke();
      ctx.setLineDash([]);

      ctx.beginPath();
      traceFeatureList(ctx, LONDON_METRO.tributaries, project, vBox, false);
      ctx.strokeStyle = pal.riverCasing;
      ctx.lineWidth = 1.1;
      ctx.stroke();

      const thamesW = clamp(2.8 / Math.max(0.25, spanLon), 2.2, 7.5);
      ctx.lineCap = 'round';
      ctx.lineJoin = 'round';
      ctx.beginPath();
      traceRing(ctx, LONDON_METRO.thames, project, false);
      ctx.strokeStyle = pal.riverCasing;
      ctx.lineWidth = thamesW * 2.15;
      ctx.stroke();
      ctx.strokeStyle = pal.riverCore;
      ctx.lineWidth = thamesW;
      ctx.stroke();
      ctx.strokeStyle = pal.riverHighlight;
      ctx.lineWidth = Math.max(0.75, thamesW * 0.34);
      ctx.stroke();

      ctx.restore();
    }

    // Layer 6: Non-Colliding Reference Labels (10px uppercase tracked Geist Mono, 0.28 opacity)
    const placedLabels = [];
    if (vs.showLabels !== false) {
      const occupied = normalizeOccupiedRects(vs);
      const candidates = [];

      const pushCities = (list, tracking) => {
        for (const c of list) {
          if (spanLon >= c.minSpan && spanLon <= c.maxSpan) {
            candidates.push({
              text: c.name.toUpperCase(), lng: c.lng, lat: c.lat,
              priority: (c.tier || 2) + (c.isRegion ? 0.5 : 0),
              isRegion: Boolean(c.isRegion), tracking: c.isRegion ? 2.6 : tracking,
            });
          }
        }
      };

      if (useLondonMetro) {
        for (const l of LONDON_METRO.labels) {
          candidates.push({ text: l.name.toUpperCase(), lng: l.lng, lat: l.lat, priority: l.priority, isRegion: false, tracking: 1.4 });
        }
      } else {
        if (useUkDetailed) pushCities(UK_DETAILED.cities, 1.5);
        if (spanLon < 85 && bboxIntersects([-12, 35, 30, 62], vBox)) pushCities(ALPS_EUROPE.cities, 1.5);
        if (useUsDetail) pushCities(US_DETAIL.cities, 1.5);
        if (spanLon >= 35) pushCities(WORLD_CONTEXT_CITIES, 1.6);
      }

      candidates.sort((a, b) => a.priority - b.priority);

      ctx.save();
      ctx.font = '500 10px ' + pal.fontMono;
      ctx.textAlign = 'center';
      ctx.textBaseline = 'middle';
      ctx.lineWidth = 2.4;
      ctx.lineJoin = 'round';
      ctx.strokeStyle = pal.labelHalo;

      const seenText = new Set();
      for (const item of candidates) {
        if (seenText.has(item.text)) continue;
        const pt = project(item.lng, item.lat);
        const x = pt[0], y = pt[1];
        if (x < 28 || x > width - 28 || y < 22 || y > height - 22) continue;

        const tw = measureTrackedWidth(ctx, item.text, item.tracking);
        const rect = { x1: x - tw * 0.5 - 8, y1: y - 9, x2: x + tw * 0.5 + 8, y2: y + 9 };
        let collides = false;
        for (let j = 0; j < occupied.length; j += 1) {
          if (rectOverlaps(rect, occupied[j])) { collides = true; break; }
        }
        if (collides) continue;

        ctx.fillStyle = item.isRegion ? pal.labelRegion : pal.labelText;
        drawTrackedMonoText(ctx, item.text, x, y, item.tracking, true);
        occupied.push(rect);
        seenText.add(item.text);
        placedLabels.push({ text: item.text, x, y, rect });
      }
      ctx.restore();
    }

    ctx.restore();
    return { placedLabels, visibleBounds: vBox, spanLon, zoom, activeLayers };
  }

