  function pickGraticuleStep(spanDeg) {
    const steps = [0.05, 0.1, 0.25, 0.5, 1, 2, 5, 10, 15, 30, 45];
    const target = spanDeg / 5.5;
    for (const s of steps) if (s >= target) return s;
    return 45;
  }

  function formatDegTick(deg, latAxis) {
    const abs = Math.abs(deg);
    const hemi = latAxis ? (deg >= 0 ? 'N' : 'S') : (deg >= 0 ? 'E' : 'W');
    if (abs < 1e-4) return '0\u00b0';
    if (Math.abs(abs - Math.round(abs)) < 1e-3) return Math.round(abs) + '\u00b0' + hemi;
    return (abs < 1 ? abs.toFixed(2) : abs.toFixed(1)).replace(/\.0+$/, '') + '\u00b0' + hemi;
  }

  function drawTopographicGrid(ctx, width, height, palette, viewState) {
    if (!ctx || !width || !height || width < 40 || height < 40) return;

    const pal = resolveAtlasPalette(palette);
    const vs = viewState || {};
    const projectFn = typeof vs.projectFn === 'function' ? vs.projectFn : null;
    const hasGeo = Boolean(projectFn || (vs.cam && vs.cam.scale > 0) || vs.bounds);

    ctx.save();
    const vLines = [], hLines = [];

    if (hasGeo) {
      const project = buildProjector(projectFn, vs, width, height);
      const metrics = resolveViewMetrics(ctx, project, { width, height, cam: vs.cam, bounds: vs.bounds, spanLon: vs.spanLon });
      const box = metrics.visibleBBox || [-180, -80, 180, 80];
      const stepLon = pickGraticuleStep(metrics.spanLon);
      const spanLat = Math.max(0.05, Math.abs(box[3] - box[1]));
      const stepLat = pickGraticuleStep(spanLat * 1.5);
      for (let lng = Math.floor(clamp(box[0], -180, 180) / stepLon) * stepLon; lng <= Math.ceil(clamp(box[2], -180, 180) / stepLon) * stepLon + 1e-6; lng += stepLon) {
        if (lng < -180 || lng > 180) continue;
        const sx = project(lng, 0)[0];
        if (sx >= 16 && sx <= width - 16) vLines.push({ pos: sx, label: formatDegTick(lng, false) });
      }
      for (let lat = Math.floor(clamp(box[1], -80, 80) / stepLat) * stepLat; lat <= Math.ceil(clamp(box[3], -80, 80) / stepLat) * stepLat + 1e-6; lat += stepLat) {
        if (lat < -80 || lat > 80) continue;
        const sy = project(0, lat)[1];
        if (sy >= 16 && sy <= height - 16) hLines.push({ pos: sy, label: formatDegTick(lat, true) });
      }
    } else {
      const spacing = width < 480 ? 72 : 96;
      const ox = ((width % spacing) * 0.5) || spacing * 0.5;
      const oy = ((height % spacing) * 0.5) || spacing * 0.5;
      for (let x = ox; x < width - 12; x += spacing) vLines.push({ pos: x, label: '' });
      for (let y = oy; y < height - 12; y += spacing) hLines.push({ pos: y, label: '' });
    }

    // Hairline micro-graticule
    ctx.beginPath();
    for (const vl of vLines) { const x = Math.round(vl.pos) + 0.5; ctx.moveTo(x, 0); ctx.lineTo(x, height); }
    for (const hl of hLines) { const y = Math.round(hl.pos) + 0.5; ctx.moveTo(0, y); ctx.lineTo(width, y); }
    ctx.strokeStyle = pal.gridLine;
    ctx.lineWidth = 1;
    ctx.stroke();

    // Micro crosshair ticks (+) at intersections
    ctx.beginPath();
    for (const vl of vLines) {
      const x = Math.round(vl.pos) + 0.5;
      for (const hl of hLines) {
        const y = Math.round(hl.pos) + 0.5;
        ctx.moveTo(x - 3.5, y); ctx.lineTo(x + 3.5, y);
        ctx.moveTo(x, y - 3.5); ctx.lineTo(x, y + 3.5);
      }
    }
    ctx.strokeStyle = pal.gridCross;
    ctx.stroke();

    // Edge latitude/longitude graduation ticks
    ctx.beginPath();
    for (const hl of hLines) { const y = Math.round(hl.pos) + 0.5; ctx.moveTo(0, y); ctx.lineTo(6, y); ctx.moveTo(width - 6, y); ctx.lineTo(width, y); }
    for (const vl of vLines) { const x = Math.round(vl.pos) + 0.5; ctx.moveTo(x, height - 6); ctx.lineTo(x, height); }
    ctx.strokeStyle = pal.gridTick;
    ctx.stroke();

    if (hasGeo && width >= 420 && vs.showEdgeTicks !== false) {
      ctx.font = '500 9px ' + pal.fontMono;
      ctx.fillStyle = pal.gridTick;
      ctx.textAlign = 'left';
      ctx.textBaseline = 'middle';
      for (const hl of hLines) if (hl.label && hl.pos >= 42 && hl.pos <= height - 48) ctx.fillText(hl.label, 10, hl.pos);
    }

    // Minimal precision Compass Rose in corner
    if (width >= 260 && height >= 180 && vs.showCompass !== false) {
      const r = width < 480 ? 13 : 16;
      const corner = vs.compassCorner || (palette && palette.compassCorner) || 'bottom-right';
      const cx = corner.includes('left') ? (width < 480 ? 22 : 28) : width - (width < 480 ? 22 : 28);
      const cy = corner.includes('top') ? (width < 480 ? 24 : 30) : height - (width < 480 ? 24 : 30);

      ctx.beginPath();
      ctx.arc(cx, cy, r, 0, Math.PI * 2);
      ctx.strokeStyle = pal.compassRing;
      ctx.lineWidth = 1;
      ctx.stroke();

      ctx.beginPath();
      ctx.moveTo(cx + r - 3, cy); ctx.lineTo(cx + r + 1.5, cy);
      ctx.moveTo(cx - r - 1.5, cy); ctx.lineTo(cx - r + 3, cy);
      ctx.moveTo(cx, cy + r - 3); ctx.lineTo(cx, cy + r + 1.5);
      ctx.stroke();

      const nLen = r * 0.62, hw = 2.6;
      ctx.beginPath();
      ctx.moveTo(cx, cy - nLen); ctx.lineTo(cx + hw, cy); ctx.lineTo(cx - hw, cy); ctx.closePath();
      ctx.fillStyle = pal.compassNeedle;
      ctx.fill();

      ctx.beginPath();
      ctx.moveTo(cx, cy + nLen * 0.8); ctx.lineTo(cx + hw, cy); ctx.lineTo(cx - hw, cy); ctx.closePath();
      ctx.strokeStyle = pal.compassRing;
      ctx.lineWidth = 0.85;
      ctx.stroke();

      ctx.font = '600 8px ' + pal.fontMono;
      ctx.fillStyle = pal.compassText;
      ctx.textAlign = 'center';
      ctx.textBaseline = 'bottom';
      ctx.fillText('N', cx, cy - r - 2.5);
    }

    ctx.restore();
  }

  // =========================================================================
  // 8. getGreatCirclePoints(lat1, lng1, lat2, lng2, steps, progress)
  // =========================================================================

  function getGreatCirclePoints(lat1, lng1, lat2, lng2, steps, progress) {
    let segCount = 48, tMax = 1;
    if (steps && typeof steps === 'object') {
      segCount = Math.max(2, Math.floor(Number(steps.steps) || 48));
      const rawT = steps.progress != null ? steps.progress : steps.t;
      tMax = rawT != null ? clamp(Number(rawT), 0, 1) : 1;
    } else {
      if (steps != null && Number.isFinite(Number(steps))) segCount = Math.max(2, Math.floor(Number(steps)));
      if (progress != null && Number.isFinite(Number(progress))) tMax = clamp(Number(progress), 0, 1);
    }

    const pLat1 = clamp(Number(lat1) || 0, MIN_LAT, MAX_LAT);
    const pLng1 = clamp(Number(lng1) || 0, -180, 180);
    const pLat2 = clamp(Number(lat2) || 0, MIN_LAT, MAX_LAT);
    const pLng2 = clamp(Number(lng2) || 0, -180, 180);
    if (tMax <= 0) return [[pLng1, pLat1]];

    const phi1 = pLat1 * DEG_TO_RAD, lam1 = pLng1 * DEG_TO_RAD;
    const phi2 = pLat2 * DEG_TO_RAD, lam2 = pLng2 * DEG_TO_RAD;
    const x1 = Math.cos(phi1) * Math.cos(lam1), y1 = Math.cos(phi1) * Math.sin(lam1), z1 = Math.sin(phi1);
    const x2 = Math.cos(phi2) * Math.cos(lam2), y2 = Math.cos(phi2) * Math.sin(lam2), z2 = Math.sin(phi2);

    const omega = Math.acos(clamp(x1 * x2 + y1 * y2 + z1 * z2, -1, 1));
    if (omega < 1e-6) {
      return [[pLng1, pLat1], [pLng1 + (pLng2 - pLng1) * tMax, clamp(pLat1 + (pLat2 - pLat1) * tMax, MIN_LAT, MAX_LAT)]];
    }

    const isAntipodal = Math.abs(Math.PI - omega) < 1e-4;
    const sinOmega = isAntipodal ? 1 : Math.sin(omega);
    const evalAt = (t) => {
      if (isAntipodal) {
        return [clamp(pLng1 + (pLng2 - pLng1) * t, -180, 180), clamp(pLat1 + (pLat2 - pLat1) * t + Math.sin(Math.PI * t) * 18, MIN_LAT, MAX_LAT)];
      }
      const a = Math.sin((1 - t) * omega) / sinOmega;
      const b = Math.sin(t * omega) / sinOmega;
      const x = a * x1 + b * x2, y = a * y1 + b * y2, z = a * z1 + b * z2;
      return [clamp(Math.atan2(y, x) * RAD_TO_DEG, -180, 180), clamp(Math.atan2(z, Math.sqrt(x * x + y * y)) * RAD_TO_DEG, MIN_LAT, MAX_LAT)];
    };

    const out = [];
    const activeSteps = Math.max(1, Math.ceil(segCount * tMax));
    for (let i = 0; i <= activeSteps; i += 1) out.push(evalAt(Math.min(tMax, (i / activeSteps) * tMax)));
    return out;
  }

