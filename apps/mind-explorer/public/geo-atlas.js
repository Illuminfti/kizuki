  function buildProjector(projectFn, viewState, width, height) {
    if (typeof projectFn === 'function') {
      return (lng, lat) => {
        const res = projectFn(lng, lat);
        return !res ? [0, 0] : (Array.isArray(res) ? res : [res.x, res.y]);
      };
    }
    const vs = viewState || {};
    if (vs.cam && Number.isFinite(vs.cam.scale) && vs.cam.scale > 0) {
      const { cx, cy, scale } = vs.cam;
      const hw = width * 0.5, hh = height * 0.5;
      return (lng, lat) => [hw + (lngToMercX(lng) - cx) * scale, hh + (latToMercY(lat) - cy) * scale];
    }
    const b = vs.bounds || { minLng: -12, maxLng: 24, minLat: 35, maxLat: 60 };
    const x0 = lngToMercX(b.minLng), x1 = lngToMercX(b.maxLng);
    const y0 = latToMercY(b.maxLat), y1 = latToMercY(b.minLat);
    const scale = Math.min(width / Math.max(1e-6, x1 - x0), height / Math.max(1e-6, y1 - y0));
    const cx = (x0 + x1) * 0.5, cy = (y0 + y1) * 0.5;
    return (lng, lat) => [width * 0.5 + (lngToMercX(lng) - cx) * scale, height * 0.5 + (latToMercY(lat) - cy) * scale];
  }

  function resolveViewMetrics(ctx, project, viewState) {
    const vs = viewState || {};
    const dpr = Number(vs.dpr) || 1;
    const width = Number(vs.width) || (ctx && ctx.canvas ? ctx.canvas.width / dpr : 1000);
    const height = Number(vs.height) || (ctx && ctx.canvas ? ctx.canvas.height / dpr : 600);
    let spanLon = Number(vs.spanLon);
    let visibleBBox = null;

    if (vs.bounds && Number.isFinite(vs.bounds.minLng) && Number.isFinite(vs.bounds.maxLng)) {
      visibleBBox = [vs.bounds.minLng, vs.bounds.minLat, vs.bounds.maxLng, vs.bounds.maxLat];
      if (!Number.isFinite(spanLon) || spanLon <= 0) spanLon = Math.abs(vs.bounds.maxLng - vs.bounds.minLng);
    } else if (vs.cam && Number.isFinite(vs.cam.scale) && vs.cam.scale > 0) {
      const halfW = (width * 0.5) / vs.cam.scale;
      const halfH = (height * 0.5) / vs.cam.scale;
      const minMy = clamp(vs.cam.cy - halfH, 0.001, 0.999);
      const maxMy = clamp(vs.cam.cy + halfH, 0.001, 0.999);
      visibleBBox = [
        (vs.cam.cx - halfW) * 360 - 180,
        RAD_TO_DEG * Math.atan(Math.sinh(Math.PI * (1 - 2 * maxMy))),
        (vs.cam.cx + halfW) * 360 - 180,
        RAD_TO_DEG * Math.atan(Math.sinh(Math.PI * (1 - 2 * minMy))),
      ];
      if (!Number.isFinite(spanLon) || spanLon <= 0) spanLon = (width / vs.cam.scale) * 360;
    } else {
      const p0 = project(0, 51.5), p1 = project(1, 51.5);
      const pxPerDeg = Math.abs(p1[0] - p0[0]);
      if (!Number.isFinite(spanLon) || spanLon <= 0) spanLon = pxPerDeg > 1e-4 ? width / pxPerDeg : 360;
      if (pxPerDeg > 1e-4) visibleBBox = [-p0[0] / pxPerDeg - 5, -85, -p0[0] / pxPerDeg + spanLon + 5, 85];
    }

    const hasExplicitZoom = vs.zoom != null && Number.isFinite(Number(vs.zoom));
    const zoom = hasExplicitZoom ? Number(vs.zoom) : Math.max(0, Math.log2(360 / Math.max(0.02, spanLon || 360)));
    return { width, height, spanLon: spanLon || 360, zoom, hasExplicitZoom, visibleBBox };
  }

  function traceRing(ctx, coords, project, closePath) {
    if (!coords || coords.length < 2) return;
    const p0 = project(coords[0][0], coords[0][1]);
    ctx.moveTo(p0[0], p0[1]);
    for (let i = 1; i < coords.length; i += 1) {
      const pt = project(coords[i][0], coords[i][1]);
      ctx.lineTo(pt[0], pt[1]);
    }
    if (closePath) ctx.closePath();
  }

  function traceFeatureList(ctx, list, project, vBox, closePath) {
    for (let i = 0; i < list.length; i += 1) {
      const f = list[i];
      if (bboxIntersects(f.bbox, vBox)) traceRing(ctx, f.coords, project, closePath);
    }
  }

  function drawTrackedMonoText(ctx, text, x, y, trackingPx, withHalo) {
    const chars = Array.from(text);
    if (!trackingPx || trackingPx <= 0.05) {
      if (withHalo && typeof ctx.strokeText === 'function') ctx.strokeText(text, x, y);
      ctx.fillText(text, x, y);
      return;
    }
    let totalW = 0;
    const widths = new Array(chars.length);
    for (let i = 0; i < chars.length; i += 1) {
      widths[i] = ctx.measureText(chars[i]).width;
      totalW += widths[i] + (i < chars.length - 1 ? trackingPx : 0);
    }
    let cursor = ctx.textAlign === 'center' ? x - totalW * 0.5 : (ctx.textAlign === 'right' || ctx.textAlign === 'end' ? x - totalW : x);
    const prevAlign = ctx.textAlign;
    ctx.textAlign = 'left';
    for (let i = 0; i < chars.length; i += 1) {
      if (withHalo && typeof ctx.strokeText === 'function') ctx.strokeText(chars[i], cursor, y);
      ctx.fillText(chars[i], cursor, y);
      cursor += widths[i] + trackingPx;
    }
    ctx.textAlign = prevAlign;
  }

  function measureTrackedWidth(ctx, text, trackingPx) {
    const base = ctx.measureText(text).width;
    return (!trackingPx || text.length <= 1) ? base : base + trackingPx * (text.length - 1);
  }

  function normalizeOccupiedRects(viewState) {
    const rects = [];
    const vs = viewState || {};
    for (const arr of [vs.occupiedRects, vs.hudSafeRects]) {
      if (!Array.isArray(arr)) continue;
      for (const r of arr) {
        if (r && Number.isFinite(r.x1) && Number.isFinite(r.y1)) rects.push({ x1: r.x1, y1: r.y1, x2: r.x2, y2: r.y2 });
      }
    }
    for (const arr of [vs.avoidPoints, vs.activePins, vs.pins]) {
      if (!Array.isArray(arr)) continue;
      for (const pt of arr) {
        if (!pt) continue;
        const x = Number.isFinite(pt.screenX) ? pt.screenX : Number(pt.x);
        const y = Number.isFinite(pt.screenY) ? pt.screenY : Number(pt.y);
        if (!Number.isFinite(x) || !Number.isFinite(y)) continue;
        const pad = Number(pt.r) || 18;
        rects.push({ x1: x - pad, y1: y - pad, x2: x + pad, y2: y + pad });
      }
    }
    return rects;
  }

